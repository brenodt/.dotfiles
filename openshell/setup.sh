#!/usr/bin/env bash
# openshell/setup.sh — idempotent "finish configuration for first use".
# Ensures the gateway runs against the right docker socket, then (provider mode)
# registers ollama.com as an OpenShell provider and points inference.local at it.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
: "${DOTFILES:=$(cd "$DIR/.." && pwd)}"
# shellcheck source=/dev/null
source "$DIR/lib.sh"

osh_require openshell docker brew

# 1. Gateway service up ---------------------------------------------------------
if ! brew services list 2>/dev/null | grep -Eq '^openshell[[:space:]]+started'; then
  osh_info "starting openshell brew service"
  brew services start openshell >/dev/null
fi

# 2. Portable docker socket -> gateway.env -------------------------------------
# Docker Desktop doesn't create the classic /var/run/docker.sock; the launchd
# service can't see the CLI's docker context, so point it explicitly. Derive the
# path from the active context so this stays correct across machines/contexts.
cfg="${XDG_CONFIG_HOME:-$HOME/.config}/openshell"; mkdir -p "$cfg"
endpoint="$(docker context inspect --format '{{.Endpoints.docker.Host}}' 2>/dev/null || true)"
if [ -n "$endpoint" ] && [ "$endpoint" != "unix:///var/run/docker.sock" ] && [ ! -S /var/run/docker.sock ]; then
  want="DOCKER_HOST=$endpoint"
  if [ ! -f "$cfg/gateway.env" ] || ! grep -qxF "$want" "$cfg/gateway.env"; then
    { echo "# generated by openshell/setup.sh — active docker context socket"; echo "$want"; } > "$cfg/gateway.env"
    osh_info "wrote $cfg/gateway.env ($want); restarting gateway"
    brew services restart openshell >/dev/null
  fi
fi

# 3. Wait for the gateway to answer --------------------------------------------
for _ in $(seq 1 10); do osh_gateway_ok && break; sleep 1; done
osh_gateway_ok || osh_fail "gateway not reachable — inspect: openshell status"
osh_success "gateway reachable"

# Build/refresh the custom sandbox image (base + pi) with a stable tag so `osh up`
# creates from it directly (no per-run build). `docker build` picks up Dockerfile changes.
if [ -f "$OSH_IMAGE_DIR/Dockerfile" ] && command -v docker >/dev/null 2>&1; then
  export DOCKER_HOST="${DOCKER_HOST:-$(osh_docker_host)}"
  osh_info "building sandbox image $OSH_IMAGE (base + pi; first time is slow)"
  if docker build -q -t "$OSH_IMAGE" "$OSH_IMAGE_DIR" >/dev/null; then
    osh_success "sandbox image ready"
  else
    osh_warn "image build failed; osh up will retry on first use"
  fi
fi

# 4. Provider mode: ollama.com provider + inference route -----------------------
mode="$(osh_mode || true)"
if [ "$mode" != "provider" ]; then
  osh_info "mode='$mode' — skipping provider config"; exit 0
fi

model="${OSH_MODEL:-glm-5.2:cloud}"
token="$(osh_ollama_token)"
[ -n "$token" ] || osh_fail "OLLAMA_API_KEY not found (Doppler) — see openshell/README.md"

# Pass the credential via env (KEY-only lookup) so the token never lands on argv.
export OPENAI_API_KEY="$token"
if openshell provider get ollama >/dev/null 2>&1; then
  openshell provider update ollama --credential OPENAI_API_KEY --config OPENAI_BASE_URL=https://ollama.com/v1 >/dev/null
  osh_success "updated provider 'ollama'"
else
  openshell provider create --name ollama --type openai --credential OPENAI_API_KEY --config OPENAI_BASE_URL=https://ollama.com/v1 >/dev/null
  osh_success "created provider 'ollama'"
fi
unset OPENAI_API_KEY

# Verify the route; fall back to --no-verify if the probe pattern isn't recognised.
openshell inference set --provider ollama --model "$model" >/dev/null 2>&1 \
  || openshell inference set --provider ollama --model "$model" --no-verify >/dev/null
osh_success "inference.local -> ollama / $model"
echo; openshell inference get
